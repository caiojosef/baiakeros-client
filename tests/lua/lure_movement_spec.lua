-- Run from the client root: luajit tests/lua/lure_movement_spec.lua
North, East, South, West = 0, 1, 2, 3
NorthEast, SouthEast, SouthWest, NorthWest = 4, 5, 6, 7
dofile('modules/game_baiakeros_helper_v2/lure_movement.lua')
local function key(p) return p.x .. ':' .. p.y end
local function range(a, b) return math.max(math.abs(a.x - b.x), math.abs(a.y - b.y)) end
local walls, holes, visits = {}, {}, {}
local bounds = { left = 88, right = 112, top = 88, bottom = 112 }
local target = { x = 100, y = 100, z = 7 }
local monsters = { target }
local function solid(p)
    return p.x < bounds.left or p.x > bounds.right or p.y < bounds.top or p.y > bounds.bottom or
        walls[key(p)] == true or holes[key(p)] == true
end
local function safe(p)
    if solid(p) then return false end
    for _, m in ipairs(monsters) do if range(p, m) == 0 then return false end end
    return true
end
local config = { wall = solid, walkable = safe, visits = function(p) return visits[key(p)] or 0 end }
local function walk(p, desired)
    local choice = assert(BaiakLureMovement.choose(p, target, monsters, desired, config))
    assert(safe(choice.position) and range(choice.position, p) == 1)
    visits[key(choice.position)] = (visits[key(choice.position)] or 0) + 1
    config.lastDirection = choice.direction
    return choice.position, choice
end

-- Keep the selected range while moving continuously around the actual target.
local p = { x = 98, y = 100, z = 7 }
for _ = 1, 24 do p = walk(p, 4) end
local diagonals = 0
for _ = 1, 16 do
    local choice
    p, choice = walk(p, 4)
    if choice.direction >= NorthEast then diagonals = diagonals + 1 end
    assert(range(p, target) == 4, 'open terrain must maintain four SQM from the target')
end
assert(diagonals <= 1, 'open terrain should use straight steps instead of unnecessary diagonals')

-- Occupied cardinal exits may leave a diagonal as the only safe escape. Keep
-- that option available rather than applying a blanket ban on diagonal steps.
local trapped = { x = 98, y = 100, z = 7 }
local escape = assert(BaiakLureMovement.choose(trapped, target, monsters, 4, {
    walkable = function(q)
        if range(q, trapped) == 1 and (q.x == trapped.x or q.y == trapped.y) then return false end
        return safe(q)
    end,
    wall = solid
}))
assert(escape.direction >= NorthEast, 'a necessary diagonal escape must remain available')

-- A vertical wall blocks the closest direct retreat. Find its open end,
-- temporarily accept another range and reach a roomy four-SQM position.
walls, holes, visits = {}, {}, {}
config.lastDirection = nil
for y = 98, 102 do walls['98:' .. y] = true end
p = { x = 99, y = 100, z = 7 }
local wentAround = false
for _ = 1, 24 do
    p = walk(p, 4)
    if p.x <= 97 and (p.y <= 97 or p.y >= 103) then wentAround = true end
end
assert(wentAround and range(p, target) == 4,
    'look-ahead must walk around the wall and recover target distance instead of pushing into it')

-- Prefer the open side of a wall over scraping along its edge at the same range.
walls, visits = {}, {}
for y = 94, 106 do walls['95:' .. y] = true end
config.lastDirection = nil
p = { x = 96, y = 100, z = 7 }
for _ = 1, 12 do p = walk(p, 4) end
assert(p.x > 96 and range(p, target) == 4,
    'an open alternative at the same target distance must move away from the wall')

-- If the only passage is narrow, use it instead of treating wall spacing as
-- an absolute rule. Never authorize an occupied tile or an unintended hole.
walls, holes, visits = {}, {}, {}
bounds = { left = 94, right = 106, top = 100, bottom = 100 }
config.lastDirection = nil
p = { x = 98, y = 100, z = 7 }
for _ = 1, 4 do p = walk(p, 4) end
assert(p.x == 96 or p.x == 95, 'a narrow corridor must still permit escape movement')
holes[key({ x = p.x - 1, y = 100 })] = true
for _ = 1, 6 do p = walk(p, 4); assert(not holes[key(p)]) end
monsters[#monsters + 1] = { x = p.x - 1, y = 100, z = 7 }
local candidate = assert(BaiakLureMovement.choose(p, target, monsters, 4, config))
assert(safe(candidate.position), 'escape must not walk onto another monster')
assert(not BaiakLureMovement.choose(p, target, monsters, 4, {
    walkable = function() return false end, wall = function() return true end
}), 'a fully trapped character must not send blind walking commands')
-- The combat corridor is frozen from actual travel, never from future nodes or
-- the steps generated by kiting. A target moving away cannot expand it.
bounds = { left = 70, right = 140, top = 70, bottom = 140 }
walls, holes, visits = {}, {}, {}
local history = {}
for x = 94, 100 do history[#history + 1] = { x = x, y = 100, z = 7 } end
p = { x = 100, y = 100, z = 7 }
local corridor = BaiakLureMovement.corridor(history, p)
config.routeDistance, config.lastDirection = corridor.distance, nil
config.patrolGoal = corridor.first
target = { x = 102, y = 100, z = 7 }
monsters = { target }
local backtracked = false
for step = 1, 100 do
    if step < 15 then target.x = target.x + 1 end
    p = walk(p, 4)
    assert(corridor.distance(p) <= 4, 'moving targets must not pull the player outside the travelled corridor')
    if p.x < 100 then backtracked = true end
end
assert(backtracked, 'Lure should retreat through the already travelled part of the route')
history[#history + 1] = { x = 130, y = 130, z = 7 }
assert(corridor.distance(history[#history]) > 4, 'later travel must not expand a frozen combat corridor')

-- Manual displacement outside the corridor allows recovery, not further drift.
target = { x = 104, y = 106, z = 7 }
monsters = { target }
p = { x = 100, y = 107, z = 7 }
config.lastDirection = nil
for _ = 1, 12 do p = walk(p, 4) end
assert(corridor.distance(p) <= 4, 'a displaced player must return to the route area')

-- Pursuing monsters change position between server steps. Distance must keep
-- issuing safe steps within the recorded cave, not orbit a stale target SQM.
walls, holes, visits = {}, {}, {}
history = {}
for x = 94, 106 do history[#history + 1] = { x = x, y = 100, z = 7 } end
p = { x = 100, y = 100, z = 7 }
corridor = BaiakLureMovement.corridor(history, p)
config.routeDistance, config.lastDirection, config.patrolGoal = corridor.distance, nil, corridor.first
target = { x = 104, y = 100, z = 7 }
monsters = { target, { x = 105, y = 102, z = 7 }, { x = 104, y = 103, z = 7 } }
local reversals, previous = 0, nil
for step = 1, 120 do
    local old = p
    local canAvoidMelee = false
    for x = -1, 1 do for y = -1, 1 do
        local q = { x = old.x + x, y = old.y + y, z = old.z }
        if (x ~= 0 or y ~= 0) and safe(q) and corridor.distance(q) <= 4 then
            local clearance = math.huge
            for _, m in ipairs(monsters) do clearance = math.min(clearance, range(q, m)) end
            if clearance >= 2 then canAvoidMelee = true end
        end
    end end
    p = walk(p, 4)
    assert(corridor.distance(p) <= 4 and range(old, p) == 1,
        'pursuing monsters must not stop movement or expand the route bounds')
    for _, m in ipairs(monsters) do assert(not canAvoidMelee or range(p, m) >= 2,
        'the first step must avoid adjacent attackers: step ' .. step .. ' player ' .. key(p) .. ' monster ' .. key(m)) end
    if previous and p.x == previous.x and p.y == previous.y then reversals = reversals + 1 end
    previous = old
    if step % 2 == 0 then
        for _, m in ipairs(monsters) do
            local dx, dy = p.x - m.x, p.y - m.y
            local nextPosition = { x = m.x, y = m.y, z = m.z }
            if math.abs(dx) >= math.abs(dy) then
                nextPosition.x = m.x + (dx > 0 and 1 or -1)
            else nextPosition.y = m.y + (dy > 0 and 1 or -1) end
            local occupied = false
            for _, other in ipairs(monsters) do
                if other ~= m and range(nextPosition, other) == 0 then occupied = true end
            end
            if not occupied then m.x, m.y = nextPosition.x, nextPosition.y end
        end
    end
end
assert(reversals < 12, 'dynamic combat must not spend the hunt bouncing between two tiles')

-- Temporary packet rejections do not turn otherwise safe exits into walls.
config.rejected = function() return true end
assert(BaiakLureMovement.choose(p, target, monsters, 4, config),
    'if all previous attempts were rejected, revalidate and retry a walkable exit')
config.rejected = nil

-- A monster wall at the virtual edge of the route must not look like a real
-- trap when an adjacent escape SQM is known and free. Detour by at most two
-- extra SQM, then recover the original corridor once the pack moves away.
history = { { x = 100, y = 100, z = 7 } }
p = { x = 96, y = 100, z = 7 }
corridor = BaiakLureMovement.corridor(history, history[1])
config.routeDistance, config.lastDirection, config.patrolGoal = corridor.distance, nil, nil
monsters = {}
for x = 96, 97 do for y = 99, 101 do
    if x ~= 96 or y ~= 100 then monsters[#monsters + 1] = { x = x, y = y, z = 7 } end
end end
target = monsters[1]
p = walk(p, 4)
assert(p.x == 95 and corridor.distance(p) == 5,
    'a blocked virtual route boundary must permit a bounded sidestep instead of stopping')
monsters = { { x = 94, y = 100, z = 7 } }
target = monsters[1]
for _ = 1, 8 do p = walk(p, 4) end
assert(corridor.distance(p) <= 4, 'an emergency sidestep must recover the frozen corridor')
config.walkable = function(q) return safe(q) and corridor.distance(q) > 6 end
assert(not BaiakLureMovement.choose({ x = 96, y = 100, z = 7 }, target, monsters, 4, config),
    'emergency escape must never expand beyond two extra SQM')
config.walkable = safe
print('Lure movement passed: target range, wall detours, safe tiles, frozen route corridor and displacement recovery')
