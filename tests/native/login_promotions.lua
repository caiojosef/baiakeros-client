-- Isolated UI regression: no credentials or game connection.
scheduleEvent(function() g_app.exit() end, 90000) -- Also allow for slow module/asset startup.
scheduleEvent(function()
    local login = rootWidget:getChildById('enterGame')
    login:getChildById('rememberEmailBox'):setChecked(false)
    login:getChildById('rememberPasswordBox'):setChecked(false)
    login:getChildById('accountNameTextEdit'):setText('')
    login:getChildById('accountPasswordTextEdit'):setText('')
    modules.client_entergame.EnterGame.show()
    local api = modules.client_bottommenu
    local menu = rootWidget:recursiveGetChildById('bottomMenu')
    local fixture = json.decode(g_resources.readFileContents('/tests/fixtures/tier_weekend_schedule.json'))
    local start = 1792242000
    local finish = start + 48 * 3600
    local active = menu:recursiveGetChildById('activeScheduleEvent'):getChildById('content')
    local upcoming = menu:recursiveGetChildById('upcomingScheduleEvent'):getChildById('content')
    local function assertGray(color, value)
        assert(color.r == value and color.g == value and color.b == value and color.a == 255)
    end
    assert(not menu:recursiveGetChildById('activeEventDate'))
    assert(not menu:recursiveGetChildById('upcomingEventDate'))
    local function at(timestamp)
        api.setEventsSchedulerTimestamp(timestamp)
        api.setEventsSchedulerCalender(fixture.eventlist)
    end
    local wednesday = start - 3 * 86400 - 10 * 3600
    at(wednesday - 1)
    assert(#active:getChildren() == 0 and #upcoming:getChildren() == 0)
    at(wednesday)
    assert(#active:getChildren() == 0 and #upcoming:getChildren() == 1)
    local upcomingRow = upcoming:getChildren()[1]
    assertGray(upcomingRow:getBackgroundColor(), 65)
    assertGray(upcomingRow:getChildById('text'):getColor(), 255)
    assert(upcomingRow:getChildById('text'):getOpacity() == 1)
    at(start - 1)
    assert(#active:getChildren() == 0 and #upcoming:getChildren() == 1)
    at(start)
    assert(#active:getChildren() == 1 and #upcoming:getChildren() == 0)
    local activeRow = active:getChildren()[1]
    assertGray(activeRow:getBackgroundColor(), 72)
    assertGray(activeRow:getChildById('text'):getColor(), 255)
    at(finish - 1)
    assert(#active:getChildren() == 1 and #upcoming:getChildren() == 0)
    at(finish)
    assert(#active:getChildren() == 0 and #upcoming:getChildren() == 0)
    at(wednesday + 7 * 86400)
    assert(#active:getChildren() == 0 and #upcoming:getChildren() == 1)
    assert(#api.getCalendarDays(os.time{year=2026,month=12,day=31}, os.time{year=2027,month=1,day=1}) == 2)
    api.setEventsSchedulerCalender({})
    assert(#active:getChildren() == 0 and #upcoming:getChildren() == 0)
    at(start + 3600)
    local title = menu:recursiveGetChildById('showOffWindowText')
    local function capture(number, expected)
        assert(title:getText():find(expected, 1, true), title:getText())
        g_logger.info('[PromotionsQA] slide ' .. number .. ': ' .. title:getText())
        g_app.doScreenshot('/slide-' .. number .. '.png')
    end
    capture(1, 'Market')
    scheduleEvent(function() capture(2, 'Helper') end, 8000)
    scheduleEvent(function() capture(3, 'Party Hunt') end, 16000)
    scheduleEvent(function()
        capture(4, 'Market')
        api.hide()
        scheduleEvent(function()
            api.show()
            assert(menu:isVisible())
            g_logger.info('[PromotionsQA] PASS: rotation, Wednesday preview, exact event boundaries, gray/white fields, no date captions and year rollover')
            g_app.exit()
        end, 800)
    end, 24000)
end, 2500)
